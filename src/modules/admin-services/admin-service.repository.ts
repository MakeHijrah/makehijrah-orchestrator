export type ServiceReferenceCounts = {
  references: Record<string, number>;
  total: number;
};

/*
 * Counts are taken per referencing table so a refusal can tell
 * the administrator exactly what is holding the service, which
 * section 13.4 requires in order to direct them to deactivate.
 */
export const countServiceReferences =
  async (
    serviceId: string,
  ): Promise<
    RepositoryResult<ServiceReferenceCounts>
  > => {
    const references: Record<
      string,
      number
    > = {};

    let total = 0;

    for (const table of SERVICE_REFERENCING_TABLES) {
      const { count, error } =
        await supabaseAdmin
          .from(table)
          .select("id", {
            count: "exact",
            head: true,
          })
          .eq(
            "service_id",
            serviceId,
          );

      if (error) {
        logDatabaseError(
          "reference count",
          { serviceId, table },
          error,
        );

        return { ok: false };
      }

      /*
       * A missing count is not zero references.
       *
       * Treating null, undefined or NaN as zero would let a
       * degraded count query authorise the deletion of a
       * referenced service, orphaning historical records that
       * section 13.5 requires be preserved. Anything that is not
       * a finite number fails closed.
       */
      if (
        typeof count !== "number" ||
        !Number.isFinite(count)
      ) {
        console.error(
          "Admin service reference count returned no usable value",
          { serviceId, table },
        );

        return { ok: false };
      }

      references[table] = count;
      total += count;
    }

    return {
      ok: true,
      value: { references, total },
    };
  };
